  function initPantheonCards() {
    currentPantheonIndex = 0;
    renderPantheonCard(0);

    var stage = document.getElementById('screen-characters');
    if (stage) {
      stage.addEventListener('touchstart', function (e) {
        if (e.touches.length > 1) return;
        swipePantheonHandler(e);
      }, { passive: true });
    }
  }

  function swipePantheonHandler(e) {
    var startX = e.touches[0].clientX;
    var endX = e.changedTouches[0].clientX;
    if (Math.abs(startX - endX) > 80) {
      if (endX < startX) nextPantheonCard();
      else prevPantheonCard();
    }
  }
  function nextPantheonCard() {
    currentPantheonIndex = (currentPantheonIndex + 1) % 6;
    renderPantheonCard(currentPantheonIndex);
  }
  function prevPantheonCard() {
    currentPantheonIndex = (currentPantheonIndex - 1 + 6) % 6;
    renderPantheonCard(currentPantheonIndex);
  }
